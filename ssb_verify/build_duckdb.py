def check_source_files(data_dir):
    """Make sure all required SSB files exist before starting."""

    required = [
        "customer.tbl",
        "supplier.tbl",
        "part.tbl",
        "date.tbl",
        "lineorder.tbl",
    ]

    missing = [
        name
        for name in required
        if not (data_dir / name).is_file()
    ]

    if missing:
        print(f"Missing files in {data_dir}:")

        for name in missing:
            print(f"  {name}")

        raise SystemExit(1)


def run_duckdb(database, sql):
    """Run SQL through the DuckDB CLI."""

    result = subprocess.run(
        ["duckdb", str(database)],
        input=sql,
        text=True
    )

    if result.returncode != 0:
        raise RuntimeError("DuckDB command failed")


def verify_database(database):
    """Print the table sizes after loading."""

    sql = """
SELECT 'customer' AS table_name, COUNT(*) AS rows FROM customer
UNION ALL
SELECT 'date', COUNT(*) FROM dim_date
UNION ALL
SELECT 'lineorder', COUNT(*) FROM lineorder
UNION ALL
SELECT 'part', COUNT(*) FROM part
UNION ALL
SELECT 'supplier', COUNT(*) FROM supplier
ORDER BY table_name;
"""

    result = subprocess.run(
        ["duckdb", str(database), "-c", sql],
        text=True
    )

    if result.returncode != 0:
        raise RuntimeError("Could not verify DuckDB database")


def main():
    parser = argparse.ArgumentParser(
        description="Build a DuckDB database from generated SSB data."
    )

    parser.add_argument(
        "--sf",
        type=int,
        required=True,
        help="SSB scale factor, e.g. 1, 10 or 50"
    )

    args = parser.parse_args()

    if args.sf <= 0:
        parser.error("--sf must be greater than 0")

    # Raw data generated by ssb-kit.
    data_dir = Path.home() / f"ssb_sf{args.sf}"

    # Generated DuckDB database used by run_all.py.
    database = VERIFY / f"ssb_sf{args.sf}.duckdb"

    check_source_files(data_dir)

    print(f"Building DuckDB SSB SF{args.sf}")
    print(f"Source:   {data_dir}")
    print(f"Database: {database}")
    print()

    # The database is generated, so rebuild it from scratch.
    database.unlink(missing_ok=True)

    sql = build_sql(data_dir)

    run_duckdb(
        database,
        sql
    )

    print()
    print("Load complete. Verifying table sizes:")
    print()

    verify_database(database)

    print()
    print(f"Created: {database}")


if __name__ == "__main__":
    main()
